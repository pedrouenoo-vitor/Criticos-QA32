import {it,expect} from 'vitest';
import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
const A='11111111-1111-4111-8111-111111111111',B='22222222-2222-4222-8222-222222222222',C='33333333-3333-4333-8333-333333333333';
it('migra V1 sem perder dados, aplica autoria, RLS, configuração e ciclos de produtividade',async()=>{
  const pg=new PGlite();
  const login=async id=>pg.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${id}';`);
  try {
    await pg.exec(`create role anon;create role authenticated;create role service_role;
      create schema auth;create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}'::jsonb);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema auth to authenticated;grant execute on function auth.uid() to authenticated;
      insert into auth.users(id,email,raw_user_meta_data) values
      ('${A}','admin@example.com','{"display_name":"Pedro"}'),('${B}','ana@example.com','{"display_name":"Ana"}'),('${C}','bia@example.com','{"display_name":"Bia"}');`);
    await pg.exec(await readFile(new URL('./schema.sql',import.meta.url),'utf8'));
    await pg.exec(`insert into public.qa_items(owner_id,lot,material,quantity,received_at,deadline) values('${A}','PENDENTE','M1',10,'2026-10-01','2026-10-10');
      insert into public.qa_items(owner_id,lot,material,quantity,received_at,deadline,released_at,responsible) values('${A}','LEGADO','M2',20,'2026-10-01','2026-10-10','2026-10-09','Carlos antigo');`);
    const migration=await readFile(new URL('./migrations/002_admin_productivity.sql',import.meta.url),'utf8');
    await pg.exec(migration);
    expect((await pg.query('select * from public.qa_items')).rows).toHaveLength(2);
    const legacy=(await pg.query('select * from public.qa_releases')).rows[0];
    expect(legacy.legacy).toBe(true);expect(legacy.actor_id).toBe(null);expect(legacy.actor_name).toBe('Carlos antigo');
    await pg.exec(`update public.qa_profiles set role='admin' where id='${A}';update public.qa_settings set comparison_days=30;`);
    await pg.exec(migration);
    expect((await pg.query('select * from public.qa_releases')).rows).toHaveLength(1);
    expect((await pg.query('select comparison_days from public.qa_settings')).rows[0].comparison_days).toBe(30);
    await login(A);
    expect((await pg.query('select * from public.qa_profiles')).rows).toHaveLength(3);
    await pg.query(`update public.qa_items set assigned_to=$1 where lot='PENDENTE'`,[B]);
    await login(B);
    expect((await pg.query('select * from public.qa_items')).rows.map(r=>r.lot)).toEqual(['PENDENTE']);
    // Atribuição forjada não controla a autoria: o gatilho usa o JWT real.
    await pg.query(`update public.qa_items set released_at='2026-10-10',responsible='Bia falsa',released_by=$1 where lot='PENDENTE'`,[C]);
    const completed=(await pg.query(`select * from public.qa_items where lot='PENDENTE'`)).rows[0];
    expect(completed.responsible).toBe('Ana');expect(completed.released_by).toBe(B);
    expect((await pg.query(`select * from public.qa_releases where not legacy`)).rows[0].actor_id).toBe(B);
    await expect(pg.query(`update public.qa_items set quantity=99 where lot='PENDENTE'`)).rejects.toThrow('Reabra');
    await expect(pg.query(`insert into public.qa_releases(item_id,owner_id,actor_name,lot,material,description,quantity,unit,received_on,released_on) values(gen_random_uuid(),$1,'Ana','x','x','',1,'PC','2026-10-01','2026-10-10')`,[B])).rejects.toThrow();
    await login(C);
    expect((await pg.query('select * from public.qa_items')).rows).toHaveLength(0);
    expect((await pg.query('select * from public.qa_releases')).rows).toHaveLength(0);
    expect((await pg.query('select * from public.qa_profiles')).rows).toHaveLength(1);
    expect((await pg.query(`update public.qa_profiles set role='admin' where id=$1 returning id`,[C])).rows).toHaveLength(0);
    expect((await pg.query('update public.qa_settings set comparison_days=2 returning id')).rows).toHaveLength(0);
    await expect(pg.query('select public.qa_reserve_user_creation()')).rejects.toThrow('administrador');
    await pg.query(`insert into public.qa_items(owner_id,lot,material,quantity,received_at) values($1,'BIA','M3',1,'2026-10-01')`,[C]);
    await expect(pg.query(`update public.qa_items set assigned_to=$1 where lot='BIA'`,[B])).rejects.toThrow('administrador');
    await login(B);
    await pg.query(`update public.qa_items set released_at=null where lot='PENDENTE'`);
    expect((await pg.query('select * from public.qa_releases where voided_at is null')).rows).toHaveLength(0);
    await pg.query(`update public.qa_items set released_at='2026-10-11',responsible='qualquer' where lot='PENDENTE'`);
    expect((await pg.query('select * from public.qa_releases')).rows).toHaveLength(2);
    expect((await pg.query('select * from public.qa_releases where voided_at is null')).rows).toHaveLength(1);
    await login(A);
    await expect(pg.query(`update public.qa_profiles set active=false where id=$1`,[A])).rejects.toThrow('administrador ativo');
    await pg.query(`delete from public.qa_items where lot='PENDENTE'`);
    expect((await pg.query('select * from public.qa_releases')).rows).toHaveLength(3);
    expect((await pg.query('select * from public.qa_history where actor_id=$1',[B])).rows.length).toBeGreaterThan(0);
    await pg.query(`update public.qa_profiles set active=false where id=$1`,[B]);
    for(let n=0;n<10;n++) await pg.query('select public.qa_reserve_user_creation()');
    await expect(pg.query('select public.qa_reserve_user_creation()')).rejects.toThrow('Limite');
    await login(B);
    expect((await pg.query('select * from public.qa_items')).rows).toHaveLength(0);
    expect((await pg.query('select * from public.qa_releases')).rows).toHaveLength(0);
    await pg.exec('reset role');
    await pg.exec(`insert into auth.users(id,email,raw_user_meta_data) values('44444444-4444-4444-8444-444444444444','novo@example.com','{"role":"admin","display_name":"Novo"}');`);
    expect((await pg.query(`select role from public.qa_profiles where email='novo@example.com'`)).rows[0].role).toBe('operator');
    await pg.exec(`set role anon`);
    await expect(pg.query('select * from public.qa_profiles')).rejects.toThrow();
  } finally {await pg.close();}
},30000);
